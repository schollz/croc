//go:build ignore

// Run from the repository root: go run ./web/scripts/generate-casefold.go
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"unicode"

	"golang.org/x/text/cases"
)

func main() {
	fold := cases.Fold()
	mapping := make([][2]string, 0)
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xd800 && r <= 0xdfff {
			continue
		}
		value := string(r)
		if folded := fold.String(value); folded != value {
			mapping = append(mapping, [2]string{value, folded})
		}
	}
	data, err := json.Marshal(mapping)
	if err != nil {
		panic(err)
	}
	// A minifier can turn object keys into identifiers from newer Unicode
	// versions than a browser's JavaScript parser supports. Map entries keep
	// every code point in string data, independent of identifier support.
	output := fmt.Sprintf("// Generated by go run ./web/scripts/generate-casefold.go; Go Unicode %s.\n// Full case folding matches receivefs.CollisionKey, including expanding folds.\n// Map entries keep newer Unicode characters in string data, never identifiers.\nconst folds = new Map<string, string>(%s);\n\nexport function foldCase(value: string) {\n  return Array.from(value.normalize(\"NFC\"), (character) => folds.get(character) ?? character).join(\"\");\n}\n", unicode.Version, data)
	if err := os.WriteFile("web/src/protocol/unicode-casefold.ts", []byte(output), 0644); err != nil {
		panic(err)
	}
}
