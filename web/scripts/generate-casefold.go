//go:build ignore

// Run from the repository root: go run ./web/scripts/generate-casefold.go
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"unicode"

	"golang.org/x/text/cases"
)

func main() {
	fold := cases.Fold()
	mapping := make(map[string]string)
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xd800 && r <= 0xdfff {
			continue
		}
		value := string(r)
		if folded := fold.String(value); folded != value {
			mapping[value] = folded
		}
	}
	data, err := json.Marshal(mapping)
	if err != nil {
		panic(err)
	}
	output := fmt.Sprintf("// Generated by go run ./web/scripts/generate-casefold.go; Go Unicode %s.\n// Full case folding matches receivefs.CollisionKey, including expanding folds.\nconst folds: Record<string, string> = %s;\n\nexport function foldCase(value: string) {\n  return Array.from(value.normalize(\"NFC\"), (character) => folds[character] ?? character).join(\"\");\n}\n", unicode.Version, data)
	if err := os.WriteFile("web/src/protocol/unicode-casefold.ts", []byte(output), 0644); err != nil {
		panic(err)
	}
}
